#!/usr/bin/env bash
# 용어 컴플라이언스 스윕 (CLAUDE.md §0-4 · FE-06)
#
# 심사 감점에 직결되는 금지어를 화면 문구에서 걸러낸다. 단순 grep은 쓸 수 없다 —
# 규정된 문구("한도·승인은 기관 심사 사항")와 코드 주석까지 잡아내서 오탐이 진짜를 덮는다.
# 실제로 스윕 도입 시점의 단순 grep은 12건을 잡았고 그 전부가 오탐이었다.
#
# 사용: bash scripts/term_sweep.sh [대상경로]   (기본 frontend/src)
# 종료 코드: 0 = 위반 없음, 1 = 위반 발견

set -uo pipefail
TARGET="${1:-frontend/src}"

# 금지어 (CLAUDE.md 용어 컴플라이언스 표)
#  - "승인"       : 판정 4단계에 "승인" 계열 단어 전면 금지
#  - "권장"       : 자금 관련 자문성 술어 금지 (정보 서술형만)
#  - "추천드/합/해": 위와 같음. **어간까지만 적는다** — 구 패턴이 "추천드립" 만 담아
#                   「추천해 드립니다」(실제로 Budget.tsx 에 있었다)를 통과시켰다.
#                   명사 "추천 점수"·"추천 상권" 은 어간 뒤 형태가 달라 걸리지 않는다.
#  - "권유/권해"   : 자금 조달 권유형 술어. 필수 고지의 "대출 권유·중개" 는 아래에서 면제한다.
#  - "보장"       : 한도·수익을 단정하는 표현. 부정형("보장하지 않습니다")은 면제한다.
#  - "조달 가능"  : "자격 요건 부합 상품 확인"으로 대체
#  - "심사역"     : "리스크 검증"으로 대체
#
# BE 검증기 `LlmResponses.BANNED_TERMS` 와 `scripts/qa_integration.py:BANNED_WORDS` 의
# 사본이다. 한 곳을 고치면 세 곳을 함께 고친다 — 갈라지면 목록이 있는데도 안 잡힌다.
PATTERN='승인|권장|추천드|추천합|추천해|권유|권해|보장|조달 가능|심사역'

# 정당한 사용 — 스펙이 오히려 이 표기를 요구하거나, 화면에 나가지 않는 문맥이다.
#  1) "한도·승인은 …", "한도·금리·승인 …" : 계약·스펙이 명시한 필수 고지 문구.
#     문구 전체로 대조하지 않는 이유는 화면 문자열이 줄바꿈으로 잘려 있어서다 —
#     "한도·승인은" 에서 줄이 끊기고 "기관 심사 사항입니다" 가 다음 줄에 온다.
#  2) "승인 여부는 …기관의 심사"          : 같은 취지의 변형
#  3) "권유·중개"                         : 필수 고지 "대출 권유·중개·자문이 아닙니다".
#     이 문구는 CLAUDE.md 가 **넣으라고** 규정한 것이라 금지어와 정반대다.
#  4) "보장하지 않"                       : 보장을 부정하는 서술. 규칙이 요구하는 형태다.
#  5) 주석                                : 화면에 나가지 않으며 대개 금지 규칙 자체를 설명한다.
#     grep -n 출력은 "파일:줄번호:" 로 시작하므로 행 선두(^)가 아니라 그 접두사 뒤를 본다.
#     JSX 주석 `{/* … */}` 도 같은 자리에 오므로 여는 중괄호를 함께 본다.
#  6) **금지어 목록 나열**                       : `LlmResponses.BANNED_TERMS` 상수와, LLM 프롬프트
#     텍스트 블록의 "「승인」·「권장」 … 같은 표현을 쓰지 마세요" 줄이다. 화면 문구가 아니라
#     금지 규칙 그 자체인데, ALLOW 가 `//`·`/*` 주석만 면제해서 Java 텍스트 블록 안의 지시문이
#     오탐으로 잡혔다(6건) — 오탐이 진짜를 덮는 것을 이 스크립트가 스스로 경계하므로 면제한다
#     (QA 리뷰 Q-09).
#     면제 조건을 **「따옴표로 정확히 감싼 금지어 + 쉼표 + 또 다른 문자열」** 로 좁힌다. 이건
#     열거의 형태이지 문장의 형태가 아니다. 화면 라벨 하나(`"승인"` 단독)는 여전히 걸린다.
#     열거가 여러 줄로 접힌 경우를 위해 「… 같은 표현을 쓰지 마세요」 줄도 함께 면제한다 —
#     금지를 지시하는 문장이지 금지어를 쓰는 문장이 아니다.
_LIST='"(승인|권장|보장|심사역|조달 가능|추천드|추천합|추천해|권유|권해)", *"|같은 표현을 쓰지 마세요'
ALLOW='한도·승인|한도·금리·승인|승인 여부는|권유·중개|보장하지 않|'"$_LIST"'|:[0-9]+:[[:space:]]*(\{?/\*|//|\*)'

echo "용어 컴플라이언스 스윕 — 대상: $TARGET"
echo

# 테스트 파일은 제외한다. 화면에 나가지 않을뿐더러, 금지어 자체를 **단언 대상**으로 적는 것이
# 그 파일들의 일이다 — `verdict.test.ts` 는 판정 문구에 "승인" 계열이 없음을 그 낱말을 써서
# 검사한다. 주석을 면제하는 것과 같은 이유다.
hits=$(grep -rnE --exclude='*.test.*' --exclude='*.spec.*' "$PATTERN" "$TARGET" 2>/dev/null \
       | grep -vE "$ALLOW" || true)

if [ -z "$hits" ]; then
  echo "✅ 위반 없음"
  exit 0
fi

echo "⚠️  검토 필요 $(echo "$hits" | wc -l | tr -d ' ')건"
echo
echo "$hits"
echo
echo "정당한 사용이라면 이 스크립트의 ALLOW 패턴에 근거와 함께 추가하라."
exit 1
